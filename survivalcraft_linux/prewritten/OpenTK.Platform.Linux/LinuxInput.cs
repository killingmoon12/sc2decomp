using System;
using System.Runtime.InteropServices;
using OpenTK.Input;

namespace OpenTK.Platform.Linux
{
    /// <summary>
    /// Collects X11 input events and exposes them through the OpenTK input drivers.
    /// </summary>
    internal static class LinuxInput
    {
        private static readonly bool[] KeysDown = new bool[256];
        private static readonly bool[] ButtonsDown = new bool[(int)MouseButton.LastButton];
        private static int MouseX;
        private static int MouseY;
        private static float Wheel;
        private static bool Connected;
        private static IntPtr _display;
        private static IntPtr _window;
        private static IntPtr _blankCursor;
        private static bool _captured;

        public static void ProcessEvent(int type, IntPtr ev, IntPtr display, IntPtr window)
        {
            switch (type)
            {
                case X11.KeyPress:
                {
                    X11.XKeyEvent ke = Marshal.PtrToStructure<X11.XKeyEvent>(ev);
                    Key key = TranslateKey(X11.XLookupKeysym(ev, 0));
                    if (key != Key.Unknown) KeysDown[(int)key] = true;
                    
                    // Extract character for text input
                    byte[] buffer = new byte[32];
                    int len = X11.XLookupString(ev, buffer, buffer.Length, IntPtr.Zero, IntPtr.Zero);
                    if (len > 0)
                    {
                        string text = System.Text.Encoding.UTF8.GetString(buffer, 0, len);
                        OnKeyPress?.Invoke(text);
                    }
                    
                    Connected = true;
                    break;
                }
                case X11.KeyRelease:
                {
                    Key key = TranslateKey(X11.XLookupKeysym(ev, 0));
                    if (key != Key.Unknown) KeysDown[(int)key] = false;
                    break;
                }
                case X11.MotionNotify:
                {
                    X11.XMotionEvent m = Marshal.PtrToStructure<X11.XMotionEvent>(ev);
                    MouseX = m.x;
                    MouseY = m.y;
                    Connected = true;
                    break;
                }
                case X11.ButtonPress:
                {
                    X11.XButtonEvent b = Marshal.PtrToStructure<X11.XButtonEvent>(ev);
                    MouseX = b.x;
                    MouseY = b.y;
                    switch (b.button)
                    {
                        case 4: Wheel += 1f; break;
                        case 5: Wheel -= 1f; break;
                        case 6: break; // horizontal wheel left
                        case 7: break; // horizontal wheel right
                        default:
                        {
                            MouseButton mb = TranslateButton(b.button);
                            if (mb != MouseButton.LastButton) ButtonsDown[(int)mb] = true;
                            break;
                        }
                    }
                    break;
                }
                case X11.ButtonRelease:
                {
                    X11.XButtonEvent b = Marshal.PtrToStructure<X11.XButtonEvent>(ev);
                    MouseX = b.x;
                    MouseY = b.y;
                    MouseButton mb = TranslateButton(b.button);
                    if (mb != MouseButton.LastButton) ButtonsDown[(int)mb] = false;
                    break;
                }
            }
        }

        public static event Action<string> OnKeyPress;

        public static void SetMousePosition(double x, double y)
        {
            MouseX = (int)x;
            MouseY = (int)y;
            if (_display != IntPtr.Zero && _window != IntPtr.Zero)
            {
                X11.XWarpPointer(_display, IntPtr.Zero, _window, 0, 0, 0, 0, (int)x, (int)y);
                X11.XFlush(_display);
            }
        }

        /// <summary>Registers the window used for pointer warping and cursor ownership.</summary>
        public static void SetWindow(IntPtr display, IntPtr window)
        {
            _display = display;
            _window = window;
        }

        /// <summary>
        /// Hides/shows the cursor for first-person mouse look. The engine re-centres
        /// the pointer every frame instead of grabbing it.
        /// </summary>
        /// <remarks>
        /// Confining the pointer with XGrabPointer(confine_to) is deliberately not
        /// done: under Xwayland the compositor turns the confinement into a pointer
        /// lock, after which real mouse motion produces no MotionNotify at all -
        /// only the events generated by our own XWarpPointer arrive, so the camera
        /// never turns. Warping back to the window centre every frame keeps the
        /// pointer inside the window without a grab and works everywhere.
        /// </remarks>
        public static void SetPointerCapture(bool captured)
        {
            if (captured == _captured) return;
            _captured = captured;
            if (_display == IntPtr.Zero || _window == IntPtr.Zero) return;
            if (captured)
            {
                if (_blankCursor == IntPtr.Zero) _blankCursor = CreateBlankCursor();
                if (_blankCursor != IntPtr.Zero) X11.XDefineCursor(_display, _window, _blankCursor);
            }
            else
            {
                X11.XUngrabPointer(_display, 0);
                X11.XUndefineCursor(_display, _window);
            }
            X11.XFlush(_display);
        }

        private static IntPtr CreateBlankCursor()
        {
            try
            {
                IntPtr pixmap = X11.XCreateBitmapFromData(_display, _window, new byte[8], 1, 1);
                if (pixmap == IntPtr.Zero) return IntPtr.Zero;
                X11.XColor black = default;
                IntPtr cursor = X11.XCreatePixmapCursor(_display, pixmap, pixmap, ref black, ref black, 0, 0);
                X11.XFreePixmap(_display, pixmap);
                return cursor;
            }
            catch
            {
                return IntPtr.Zero;
            }
        }

        public static KeyboardState GetKeyboardState()
        {
            KeyboardState state = new KeyboardState();
            state.IsConnected = true;
            for (int i = 1; i < KeysDown.Length && i < (int)Key.LastKey; i++)
            {
                if (KeysDown[i]) state[(Key)i] = true;
            }
            return state;
        }

        public static MouseState GetMouseState()
        {
            MouseState state = new MouseState();
            state.IsConnected = true;
            state.X = MouseX;
            state.Y = MouseY;
            state.WheelPrecise = Wheel;
            for (int i = 0; i < ButtonsDown.Length; i++)
            {
                if (ButtonsDown[i]) state[(MouseButton)i] = true;
            }
            return state;
        }

        private static MouseButton TranslateButton(uint xbutton)
        {
            switch (xbutton)
            {
                case 1: return MouseButton.Left;
                case 2: return MouseButton.Middle;
                case 3: return MouseButton.Right;
                case 8: return MouseButton.Button1;
                case 9: return MouseButton.Button2;
                case 10: return MouseButton.Button3;
                case 11: return MouseButton.Button4;
                case 12: return MouseButton.Button5;
                case 13: return MouseButton.Button6;
                case 14: return MouseButton.Button7;
                case 15: return MouseButton.Button8;
                case 16: return MouseButton.Button9;
                default: return MouseButton.LastButton;
            }
        }

        private static Key TranslateKey(ulong keysym)
        {
            // Printable ASCII: digits, letters and common punctuation.
            if (keysym >= '0' && keysym <= '9') return Key.Number0 + (int)(keysym - '0');
            if (keysym >= 'a' && keysym <= 'z') return Key.A + (int)(keysym - 'a');
            if (keysym >= 'A' && keysym <= 'Z') return Key.A + (int)(keysym - 'A');
            switch (keysym)
            {
                case 0x0020: return Key.Space;
                case 0x0027: return Key.Quote;
                case 0x002C: return Key.Comma;
                case 0x002D: return Key.Minus;
                case 0x002E: return Key.Period;
                case 0x002F: return Key.Slash;
                case 0x003B: return Key.Semicolon;
                case 0x003D: return Key.Plus;
                case 0x005B: return Key.BracketLeft;
                case 0x005C: return Key.BackSlash;
                case 0x005D: return Key.BracketRight;
                case 0x0060: return Key.Tilde;
                // Function keys.
                case 0xFFBE: return Key.F1;
                case 0xFFBF: return Key.F2;
                case 0xFFC0: return Key.F3;
                case 0xFFC1: return Key.F4;
                case 0xFFC2: return Key.F5;
                case 0xFFC3: return Key.F6;
                case 0xFFC4: return Key.F7;
                case 0xFFC5: return Key.F8;
                case 0xFFC6: return Key.F9;
                case 0xFFC7: return Key.F10;
                case 0xFFC8: return Key.F11;
                case 0xFFC9: return Key.F12;
                // Editing / navigation.
                case 0xFF08: return Key.BackSpace;
                case 0xFF09: return Key.Tab;
                case 0xFF0D: return Key.Enter;
                case 0xFF1B: return Key.Escape;
                case 0xFF50: return Key.Home;
                case 0xFF51: return Key.Left;
                case 0xFF52: return Key.Up;
                case 0xFF53: return Key.Right;
                case 0xFF54: return Key.Down;
                case 0xFF55: return Key.PageUp;
                case 0xFF56: return Key.PageDown;
                case 0xFF57: return Key.End;
                case 0xFF63: return Key.Insert;
                case 0xFFFF: return Key.Delete;
                // Modifiers and locks.
                case 0xFFE1: return Key.ShiftLeft;
                case 0xFFE2: return Key.ShiftRight;
                case 0xFFE3: return Key.ControlLeft;
                case 0xFFE4: return Key.ControlRight;
                case 0xFFE5: return Key.CapsLock;
                case 0xFFE9: return Key.AltLeft;
                case 0xFFEA: return Key.AltRight;
                case 0xFFEB: return Key.WinLeft;
                case 0xFFEC: return Key.WinRight;
                case 0xFF7F: return Key.NumLock;
                case 0xFF14: return Key.ScrollLock;
                case 0xFF13: return Key.Pause;
                case 0xFF61: return Key.PrintScreen;
                // Keypad.
                case 0xFFB0: return Key.Keypad0;
                case 0xFFB1: return Key.Keypad1;
                case 0xFFB2: return Key.Keypad2;
                case 0xFFB3: return Key.Keypad3;
                case 0xFFB4: return Key.Keypad4;
                case 0xFFB5: return Key.Keypad5;
                case 0xFFB6: return Key.Keypad6;
                case 0xFFB7: return Key.Keypad7;
                case 0xFFB8: return Key.Keypad8;
                case 0xFFB9: return Key.Keypad9;
                case 0xFFAF: return Key.KeypadDivide;
                case 0xFFAA: return Key.KeypadMultiply;
                case 0xFFAD: return Key.KeypadSubtract;
                case 0xFFAB: return Key.KeypadAdd;
                case 0xFFAE: return Key.KeypadDecimal;
                case 0xFF8D: return Key.KeypadEnter;
                default: return Key.Unknown;
            }
        }
    }
}
